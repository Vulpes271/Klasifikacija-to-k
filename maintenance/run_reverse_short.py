def room(p, bounds):
    return (p[:,0]>=bounds[0]) & (p[:,0]<=bounds[2]) & (p[:,1]>=bounds[1]) & (p[:,1]<=bounds[3])

def wrap(x): return (x+np.pi)%(2*np.pi)-np.pi

def points(ranges, laser, transform, count):
    good = np.flatnonzero(np.isfinite(ranges)&(ranges>laser['range_min'])&(ranges<laser['range_max']))
    if not len(good): return np.empty((0,2))
    chosen = good[np.unique(np.linspace(0,len(good)-1,min(count,len(good))).astype(int))]
    return scan_points(ranges,laser,transform)[chosen,:2]

class Matcher:
    """Likelihood field, exhaustive coarse SE(2) search + local refinement.

    The same candidates, beam budgets and optimization limits apply to all maps.
    No GT or odometry is available to this class.
    """
    def __init__(self, grid, meta):
        self.meta = meta
        self.field = np.minimum(distance_transform_edt(grid!=100)*meta['resolution'], .6)

    def residual(self, poses, pts, linear=False):
        c = np.cos(poses[:,2,None]); s = np.sin(poses[:,2,None])
        x = poses[:,0,None]+c*pts[:,0]-s*pts[:,1]
        y = poses[:,1,None]+s*pts[:,0]+c*pts[:,1]
        u = (x-self.meta['origin'][0])/self.meta['resolution']-.5
        v = (y-self.meta['origin'][1])/self.meta['resolution']-.5
        return map_coordinates(self.field,[v,u],order=1 if linear else 0, mode='constant',cval=.6,prefilter=False)

    def scores(self, poses, pts):
        return np.mean(self.residual(poses,pts)**2,axis=1)

    def refine(self, initial, pts):
        if not len(pts): return np.full(3,np.nan)
        fit = least_squares(lambda p:self.residual(p[None],pts,True)[0],initial,
            bounds=(initial-[.6,.6,np.deg2rad(8)],initial+[.6,.6,np.deg2rad(8)]),
            diff_step=1e-4, max_nfev=35, ftol=1e-5, xtol=1e-5, gtol=1e-5)
        fit.x[2] = wrap(fit.x[2]); return fit.x

    def global_match(self, candidates, coarse, fine):
        if not len(coarse): return np.full(3,np.nan), candidates[:32].copy()
        scores = np.concatenate([self.scores(candidates[i:i+2048],coarse) for i in range(0,len(candidates),2048)])
        # Preserve spatially distinct modes before local optimization.
        selected=[]
        for j in np.argsort(scores):
            p=candidates[j]
            if all(np.linalg.norm(p[:2]-q[:2])>.5 or abs(wrap(p[2]-q[2]))>np.deg2rad(15) for q in selected):
                selected.append(p)
                if len(selected)==24: break
        refined=np.array([self.refine(p,fine) for p in selected])
        return refined[np.argmin(self.scores(refined,fine))], refined


def deltas(odom, enabled):
    """ZERO branch returns before any measured relative motion is computed."""
    result=np.zeros((len(odom),3))
    if not enabled: return result
    d=np.diff(odom[:,:2],axis=0); c=np.cos(odom[:-1,2]); s=np.sin(odom[:-1,2])
    result[1:,0]=c*d[:,0]+s*d[:,1];result[1:,1]=-s*d[:,0]+c*d[:,1]
    result[1:,2]=wrap(np.diff(odom[:,2]));return result


def sequential(matcher, scans, fine_scans, candidates, motion, allowed, seed):
    rng=np.random.default_rng(seed); count=2048
    estimates=[]; durations=[]
    # Identical exhaustive broad prior on the first scan, all yaw angles.
    begin=time.perf_counter(); estimate,modes=matcher.global_match(candidates,scans[0],fine_scans[0])
    particles=modes[rng.integers(len(modes),size=count)].copy()
    particles+=rng.normal(size=particles.shape)*[.15,.15,.08]
    estimates.append(estimate);durations.append(time.perf_counter()-begin)
    for i in range(1,len(scans)):
        begin=time.perf_counter(); d=motion[i];c=np.cos(particles[:,2]);s=np.sin(particles[:,2])
        particles[:,0]+=c*d[0]-s*d[1];particles[:,1]+=s*d[0]+c*d[1];particles[:,2]+=d[2]
        # Same process noise in both arms, even with zero predicted motion.
        particles+=rng.normal(size=particles.shape)*[.025,.025,.015]
        inject=40
        particles[:inject,:2]=allowed[rng.integers(len(allowed),size=inject)]
        particles[:inject,2]=rng.uniform(-np.pi,np.pi,inject)
        pts=scans[i]
        if len(pts):
            costs=matcher.scores(particles,pts)
            estimate=matcher.refine(particles[np.argmin(costs)],fine_scans[i])
            weights=np.exp(-(costs-costs.min())/.008);weights/=weights.sum()
            # Systematic resampling; feedback comes from this scan only.
            indices=np.searchsorted(np.cumsum(weights),(rng.random()+np.arange(count))/count)
            particles=particles[np.minimum(indices,count-1)].copy()
            particles[-256:]=estimate+rng.normal(size=(256,3))*[.04,.04,.025]
        else: estimate=np.full(3,np.nan)
        particles[:,2]=wrap(particles[:,2]);estimates.append(estimate);durations.append(time.perf_counter()-begin)
        if i%1000==0: print('sequential',i,'/',len(scans),flush=True)
    return np.array(estimates),np.array(durations)


def metrics_rows(kind, variant, indices, times, gt, has_gt, estimates, duration, bounds):
    rows=[]
    for k,i in enumerate(indices):
        valid=bool(has_gt[i] and np.isfinite(gt[i]).all()); present=bool(np.isfinite(estimates[k]).all())
        pos=float(np.linalg.norm(estimates[k,:2]-gt[i,:2])) if valid and present else None
        yaw=float(abs(np.rad2deg(wrap(estimates[k,2]-gt[i,2])))) if valid and present else None
        rows.append(dict(kind=kind,variant=variant,scan_index=int(i),timestamp=float(times[i]),
            room=bool(room(gt[i:i+1],bounds)[0]) if valid else False,has_gt=valid,has_estimate=present,
            x=float(estimates[k,0]) if present else None,y=float(estimates[k,1]) if present else None,
            yaw=float(estimates[k,2]) if present else None,gt_x=float(gt[i,0]) if valid else None,
            gt_y=float(gt[i,1]) if valid else None,gt_yaw=float(gt[i,2]) if valid else None,
            position_error_m=pos,yaw_error_deg=yaw,success=bool(pos is not None and pos<.1 and yaw<4),
            processing_s=float(duration[k])))
    return rows


